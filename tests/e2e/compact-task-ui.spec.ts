test('die Notiz gehört zur klickbaren und ziehbaren Aufgabenfläche', async ({ page }) => {
  await desktop.register(page, desktop.uniqueEmail('task-surface'))
  await desktop.createList(page, 'Testliste')
  await desktop.createTask(page, 'Mit Notiz')
  const editor = await desktop.openTaskEditor(page, 'Mit Notiz')
  await editor.getByLabel('Notiz', { exact: true }).fill('Hier muss Ziehen ebenfalls funktionieren.\nAuch die zweite Zeile bleibt erhalten.')
  await editor.getByRole('button', { name: 'Speichern', exact: true }).click()
  const item = desktop.taskItem(page, 'Mit Notiz')
  const description = item.getByTestId('task-description')
  await description.click()
  await expect(item.getByRole('button', { name: 'Notiz einklappen', exact: true })).toBeVisible()
  await expect(editor).toBeHidden()
  await item.getByRole('button', { name: 'Notiz einklappen', exact: true }).click()
  await item.getByText('Mit Notiz', { exact: true }).click()
  await expect(editor).toBeVisible({ timeout: 2000 })
  await editor.getByRole('button', { name: 'Schließen', exact: true }).click()
  const box = (await description.boundingBox())!
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
  await page.mouse.down()
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2 + 10, { steps: 3 })
  try { await expect(page.locator('[data-dnd-dragging]')).toBeVisible({ timeout: 2000 }) }
  finally { await page.keyboard.press('Escape'); await page.mouse.up() }
  await expect(editor).toBeHidden()
})

