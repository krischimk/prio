test('ungültiges Datum und ungültige Uhrzeit überschreiben keine gespeicherten Werte', async ({ page, request }) => {
  await desktop.register(page, desktop.uniqueEmail('invalid-date'))
  await desktop.createList(page, 'Termine')
  await desktop.createTask(page, 'Termin')
  const editor = await desktop.openTaskEditor(page, 'Termin')
  await setDueAt(editor, '2027-06-01T18:20')
  await editor.getByRole('button', { name: 'Speichern', exact: true }).click()
  await expect(editor).toBeHidden()
  await expect.poll(async () => (await desktop.serverState(request)).tasks[0]?.description).toBeNull()
  await desktop.openTaskEditor(page, 'Termin')
  await editor.getByRole('button', { name: 'Fälligkeit und Wiederholung bearbeiten' }).click()
  const day = editor.getByLabel('Fällig am', { exact: true })
  await day.fill('31.02.2027')
  await editor.getByRole('button', { name: 'Speichern', exact: true }).click()
  await expect(editor).toBeVisible()
  expect(await day.evaluate(element => (element as HTMLInputElement).validity.valid)).toBe(false)
  await day.fill('02.06.2027')
  await day.press('Tab')
  const clock = editor.getByLabel('Fällig am: Uhrzeit', { exact: true })
  await clock.fill('25:60')
  await editor.getByRole('button', { name: 'Speichern', exact: true }).click()
  await expect(editor).toBeVisible()
  expect(await clock.evaluate(element => (element as HTMLInputElement).validity.valid)).toBe(false)
  await editor.getByRole('button', { name: 'Fällig am: Uhrzeit wählen', exact: true }).click()
  await editor.getByLabel('Fällig am: Uhrzeit: Stunde', { exact: true }).selectOption('19')
  await editor.getByLabel('Fällig am: Uhrzeit: Minute', { exact: true }).selectOption('25')
  await editor.getByRole('button', { name: 'Speichern', exact: true }).click()
  await expect(editor).toBeHidden()
  await desktop.openTaskEditor(page, 'Termin')
  await editor.getByRole('button', { name: 'Fälligkeit und Wiederholung bearbeiten' }).click()
  await expect(day).toHaveValue('02.06.2027')
  await expect(clock).toHaveValue('19:25')
})

test('auch die chronologische Gesamtansicht kann Aufgaben in die Seitenleiste ziehen', async ({ page, request }) => {
  await desktop.register(page, desktop.uniqueEmail('newest-sidebar'))
  await desktop.createList(page, 'Arbeit')
  await desktop.createTask(page, 'Ältere Aufgabe')
  await desktop.createList(page, 'Einkaufen')
  await desktop.createTask(page, 'Neuere Aufgabe')
  await openOverview(page, false)
  const settings = await overviewSettings(page)
  for (const name of ['Arbeit', 'Einkaufen']) {
    await settings.getByLabel(name, { exact: true }).check()
    await expect(settings.getByLabel(name, { exact: true })).toBeEnabled()
  }
  await settings.getByRole('button', { name: 'Schließen', exact: true }).click()
  await setOverviewMode(page, 'newest')
  await expect(page.getByTestId('overview-task')).toHaveText([/Neuere Aufgabe.*Einkaufen/s, /Ältere Aufgabe.*Arbeit/s])
  const source = page.getByTestId('overview-task').filter({ hasText: 'Neuere Aufgabe' })
  const box = (await source.getByRole('button', { name: 'Bearbeiten', exact: true }).boundingBox())!
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
  await page.mouse.down()
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2 + 10, { steps: 3 })
  await expect(page.locator('[data-dnd-dragging]')).toBeVisible()
  const target = page.getByRole('complementary', { name: 'Listen' }).getByRole('button', { name: 'Arbeit', exact: true })
  const destination = (await target.boundingBox())!
  await page.mouse.move(destination.x + destination.width / 2, destination.y + destination.height / 2, { steps: 15 })
  await expect(target).toHaveAttribute('data-drop-target', 'true')
  await page.mouse.up()
  await expect(source).toHaveCount(1)
  await expect(source).toContainText('Arbeit')
  await expect(page.getByTestId('overview-task')).toHaveText([/Neuere Aufgabe.*Arbeit/s, /Ältere Aufgabe.*Arbeit/s])
  await expect.poll(async () => (await desktop.serverState(request)).tasks.filter(task => task.section_id !== null)).toHaveLength(0)
  await desktop.selectList(page, 'Arbeit')
  await expect(desktop.taskItems(page)).toHaveText(['Ältere Aufgabe', 'Neuere Aufgabe'])
})

test('Ziehung auf die Seitenleiste wechselt die Liste und Löschen lässt sich rückgängig machen', async ({ page, request }, info) => {
  await desktop.register(page, desktop.uniqueEmail('sidebar-drag'))
  await desktop.createList(page, 'Einkaufen')
  await desktop.createTask(page, 'Mitnehmen')
  const editor = await desktop.openTaskEditor(page, 'Mitnehmen')
  await editor.getByLabel('Notiz', { exact: true }).fill('Auch über die Notiz ziehbar')
  await editor.getByRole('button', { name: 'Speichern', exact: true }).click()
  await expect(editor).toBeHidden()
  await desktop.createList(page, 'Arbeit')
  await desktop.createTask(page, 'Vorhanden')
  await desktop.selectList(page, 'Einkaufen')
  await page.context().setOffline(true)
  const source = desktop.taskItem(page, 'Mitnehmen')
  const id = await source.getAttribute('data-id')
  const box = (await source.getByTestId('task-description').boundingBox())!
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
  await page.mouse.down()
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2 + 10, { steps: 3 })
  await expect(page.locator('[data-dnd-dragging]')).toBeVisible()
  const target = page.getByRole('complementary', { name: 'Listen' }).getByRole('button', { name: 'Arbeit', exact: true })
  const destination = (await target.boundingBox())!
  await page.mouse.move(destination.x + destination.width / 2, destination.y + destination.height / 2, { steps: 15 })
  await expect(target).toHaveAttribute('data-drop-target', 'true')
  await expect(page.locator('[data-dnd-dragging]').getByText('Mitnehmen', { exact: true })).toBeInViewport()
  await page.screenshot({ path: info.outputPath('sidebar-drag.png') })
  await page.mouse.up()
  await expect(source).toHaveCount(0)
  await page.context().setOffline(false)
  await page.getByRole('button', { name: 'Jetzt synchronisieren', exact: true }).click()
  await expect.poll(async () => {
    const state = await desktop.serverState(request)
    return state.tasks.find(task => task.id === id)?.list_id === state.lists.find(list => list.name === 'Arbeit')?.id
  }).toBe(true)
  await desktop.selectList(page, 'Arbeit')
  await expect(desktop.taskItems(page)).toHaveText(['Vorhanden', 'MitnehmenAuch über die Notiz ziehbar'])
  const item = desktop.taskItem(page, 'Mitnehmen')
  await item.hover()
  await item.getByRole('button', { name: 'Aufgabe löschen: Mitnehmen', exact: true }).click()
  await expect(item).toHaveCount(0)
  await page.getByTestId('undo-bar').getByRole('button', { name: 'Rückgängig', exact: true }).click()
  await expect(item).toBeVisible()
  await expect(item).toContainText('Auch über die Notiz ziehbar')
})
