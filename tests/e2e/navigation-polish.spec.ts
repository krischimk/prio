import { expect, test } from '@playwright/test'
import * as desktop from './support/helpers'
import * as phone from './support/mobile'
import { formatCalendarDay } from '../../src/ui/datetime'
import { checkListSorting } from './support/listNavigation'
import { setDueAt } from './support/taskForms'
import { openAccount, setTheme } from './support/theme'

test.beforeEach(async ({ request }) => desktop.resetServer(request))

for (const mobile of [false, true]) test.describe(mobile ? 'Bedienung Telefon' : 'Bedienung breit', () => {
  test.use({ viewport: mobile ? { width: 390, height: 844 } : { width: 1280, height: 800 }, hasTouch: mobile, timezoneId: 'Europe/Berlin' })
  test('Fälligkeit und Erinnerung öffnen Kalender und anschließend Uhrzeit direkt', async ({ page }, info) => {
    const now = new Date()
    await page.clock.setFixedTime(now)
    const today = new Intl.DateTimeFormat('sv-SE', { timeZone: 'Europe/Berlin' }).format(now)
    const tomorrow = new Date(Date.parse(`${today}T12:00:00Z`) + 86400000).toISOString().slice(0, 10)
    const afterTomorrow = new Date(Date.parse(`${today}T12:00:00Z`) + 2 * 86400000).toISOString().slice(0, 10)
    await (mobile ? phone.register : desktop.register)(page, desktop.uniqueEmail('date-shortcut'))
    await (mobile ? phone.createList : desktop.createList)(page, 'Termine')
    await (mobile ? phone.createTask : desktop.createTask)(page, 'Kalenderfolge')
    const editor = await desktop.openTaskEditor(page, 'Kalenderfolge')
    await editor.getByRole('button', { name: 'Fälligkeit und Wiederholung bearbeiten', exact: true }).click()
    await page.getByRole('button', { name: formatCalendarDay(tomorrow), exact: true }).click()
    const clock = page.getByRole('dialog', { name: 'Uhrzeit wählen', exact: true })
    await expect(clock).toBeVisible()
    await clock.getByLabel('Fällig am: Uhrzeit: Stunde', { exact: true }).selectOption('14')
    await clock.getByLabel('Fällig am: Uhrzeit: Minute', { exact: true }).selectOption('30')
    await expect(clock).toBeHidden()
    await expect(editor.getByLabel('Fällig am: Uhrzeit', { exact: true })).toHaveValue('14:30')
    await editor.getByRole('button', { name: 'Erinnerung hinzufügen', exact: true }).click()
    await page.getByRole('button', { name: formatCalendarDay(afterTomorrow), exact: true }).click()
    await expect(clock).toBeVisible()
    await clock.getByLabel('Erinnerung am: Uhrzeit: Stunde', { exact: true }).selectOption('09')
    await clock.getByLabel('Erinnerung am: Uhrzeit: Minute', { exact: true }).selectOption('15')
    await editor.getByRole('button', { name: 'Speichern', exact: true }).click()
    await expect(editor).toBeHidden()
    await desktop.openTaskEditor(page, 'Kalenderfolge')
    await editor.getByRole('button', { name: 'Fälligkeit und Wiederholung bearbeiten', exact: true }).click()
    if (tomorrow.slice(0, 7) !== today.slice(0, 7)) await page.getByRole('button', { name: 'Voriger Monat', exact: true }).click()
    await expect(page.getByRole('button', { name: formatCalendarDay(today), exact: true })).toBeVisible()
    await page.screenshot({ path: info.outputPath('calendar-today.png') })
  })
  test('Browser-Zurück schließt Dialoge und besucht anschließend die vorige Liste', async ({ page }) => {
    await (mobile ? phone.register : desktop.register)(page, desktop.uniqueEmail('history'))
    await (mobile ? phone.createList : desktop.createList)(page, 'Arbeit')
    await (mobile ? phone.createTask : desktop.createTask)(page, 'Eintrag')
    await (mobile ? phone.createList : desktop.createList)(page, 'Einkaufen')
    if (mobile) {
      await phone.openMenu(page)
      await page.getByRole('dialog', { name: 'Menü', exact: true }).getByRole('button', { name: 'Arbeit', exact: true }).click()
    } else await desktop.selectList(page, 'Arbeit')
    const editor = await desktop.openTaskEditor(page, 'Eintrag')
    await page.goBack()
    await expect(editor).toBeHidden()
    await expect(page.getByTestId(mobile ? 'app-bar-title' : 'list-title')).toHaveText('Arbeit')
    await page.goBack()
    await expect(page.getByTestId(mobile ? 'app-bar-title' : 'list-title')).toHaveText('Einkaufen')
    await page.goForward()
    await expect(page.getByTestId(mobile ? 'app-bar-title' : 'list-title')).toHaveText('Arbeit')
    if (mobile) await phone.openMenu(page)
    await page.getByRole('button', { name: 'Konto', exact: true }).click()
    const account = page.getByRole('dialog', { name: 'Konto', exact: true })
    await expect(account).toBeVisible()
    await page.goBack()
    await expect(account).toBeHidden()
    await expect(page.getByRole('dialog', { name: 'Menü', exact: true })).toBeHidden()
  })
  test('heller Modus bleibt nach Neustart erhalten', async ({ page }, info) => {
    await (mobile ? phone.register : desktop.register)(page, desktop.uniqueEmail('light-mode'))
    await (mobile ? phone.createList : desktop.createList)(page, 'Darstellung')
    await (mobile ? phone.createTask : desktop.createTask)(page, 'Eine Aufgabe')
    await setTheme(page, mobile, 'light')
    await page.screenshot({ path: info.outputPath('light-mode.png') })
    await page.reload()
    const account = await openAccount(page, mobile)
    await expect(account.getByRole('combobox', { name: 'Farbschema', exact: true })).toHaveValue('light')
    await account.getByRole('combobox', { name: 'Farbschema', exact: true }).selectOption('dark')
    await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  })
  test('Listen umsortieren, verstecken und zurückziehen', async ({ page }) => {
    await checkListSorting(page, mobile)
  })
  test('Listenposition und Verstecken sind ohne Ziehen bedienbar', async ({ page }) => {
    await (mobile ? phone.register : desktop.register)(page, desktop.uniqueEmail('list-buttons'))
    for (const name of ['A', 'B']) await (mobile ? phone.createList : desktop.createList)(page, name)
    if (mobile) await page.getByTestId('app-bar-title').click()
    else await desktop.openListSettings(page)
    const settings = page.getByRole('dialog', { name: 'Liste verwalten', exact: true })
    await settings.getByRole('button', { name: 'Liste nach oben', exact: true }).click()
    await expect(settings.getByRole('button', { name: 'Liste nach oben', exact: true })).toBeDisabled()
    await settings.getByRole('button', { name: 'Liste verstecken', exact: true }).click()
    await expect(settings.getByRole('button', { name: 'Liste anzeigen', exact: true })).toBeVisible()
    await settings.getByRole('button', { name: 'Schließen', exact: true }).click()
    if (mobile) await phone.openMenu(page)
    const nav = page.getByRole('navigation', { name: 'Listennavigation' })
    await expect(nav.getByTestId('list-of-lists').getByRole('button')).toHaveText(['A'])
    await nav.getByRole('button', { name: /^Versteckt/ }).click()
    await expect(nav.getByRole('list', { name: 'Versteckte Listen' }).getByRole('button', { name: 'B', exact: true })).toBeVisible()
  })
  test('nächste Wiederholung bleibt bis zur bisherigen Fälligkeit gedämpft, auch offline', async ({ page, request }, info) => {
    const now = new Date()
    const due = new Date(now.getTime() + 120000)
    due.setSeconds(0, 0)
    const localDue = new Intl.DateTimeFormat('sv-SE', { timeZone: 'Europe/Berlin', year: 'numeric', month: '2-digit', day: '2-digit', hour: '2-digit', minute: '2-digit', hourCycle: 'h23' }).format(due).replace(' ', 'T')
    // App und Auth-Mock bleiben auf derselben Uhr. Eine künstlich um Stunden
    // vorgerückte App würde hier die echte Test-Sitzung verfrüht erneuern.
    await page.clock.install({ time: now })
    await (mobile ? phone.register : desktop.register)(page, desktop.uniqueEmail('upcoming-repeat'))
    await (mobile ? phone.createList : desktop.createList)(page, 'Routinen')
    await (mobile ? phone.createTask : desktop.createTask)(page, 'Täglich lesen')
    const editor = await desktop.openTaskEditor(page, 'Täglich lesen')
    await setDueAt(editor, localDue)
    await editor.getByLabel('Wiederholung', { exact: true }).selectOption('daily')
    await editor.getByRole('button', { name: 'Speichern', exact: true }).click()
    await expect(editor).toBeHidden()
    await page.getByLabel('Aufgabe erledigen: Täglich lesen', { exact: true }).click()
    const row = page.getByTestId('task-row').filter({ hasText: 'Täglich lesen' })
    await expect(row).toContainText('Nächste Wiederholung')
    await expect.poll(async () => (await desktop.serverState(request)).tasks.some(task => !task.completed && task.available_from === due.toISOString())).toBe(true)
    await page.screenshot({ path: info.outputPath('upcoming-repeat.png') })
    await page.context().setOffline(true)
    await page.clock.fastForward('03:00')
    await expect(row).not.toContainText('Nächste Wiederholung')
    await expect(row).toContainText('Täglich')
    if (mobile) {
      // Browser bleiben unter ihrer 768px-Schwelle im mobilen Bedienmodell;
      // die native App verwendet für Telefone im Querformat 1024px.
      await page.setViewportSize({ width: 740, height: 360 })
      await expect(row).toBeVisible()
      await page.screenshot({ path: info.outputPath('phone-landscape.png') })
    }
  })
})
