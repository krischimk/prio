import { selectOption } from './support/select'
import { expectOverviewMode, moreOptions, setOverviewMode } from './support/taskForms'
import { expect, test } from '@playwright/test'
import * as desktop from './support/helpers'
import * as phone from './support/mobile'
import { openOverview, overviewSettings, rememberOverviewTarget } from './support/overview'
import { setTheme } from './support/theme'

for (const mobile of [false, true]) test.describe(mobile ? 'Gesamtansicht Telefon' : 'Gesamtansicht breit', () => {
  test.use({ viewport: mobile ? { width: 390, height: 844 } : { width: 1280, height: 800 }, hasTouch: mobile })
  test.beforeEach(async ({ request }) => { await desktop.resetServer(request) })
  const register = mobile ? phone.register : desktop.register
  const createList = mobile ? phone.createList : desktop.createList
  const createTask = mobile ? phone.createTask : desktop.createTask

  test('beide Sortierungen behalten Herkunft und bestehende Listenreihenfolge', async ({ page }) => {
    await register(page, desktop.uniqueEmail('overview-order'))
    await createList(page, 'Arbeit')
    await desktop.listAction(page, 'Symbol ändern')
    await page.getByTestId('icon-picker').getByRole('button', { name: 'Prio', exact: true }).click()
    await expect(page.getByRole('dialog', { name: 'Liste verwalten', exact: true })).toBeHidden()
    await createTask(page, 'Ältere Arbeit')
    await createTask(page, 'Neuere Arbeit')
    await createList(page, 'Einkaufen')
    await desktop.listAction(page, 'Symbol ändern')
    await page.getByTestId('icon-picker').getByRole('button', { name: 'Einkauf', exact: true }).click()
    await expect(page.getByRole('dialog', { name: 'Liste verwalten', exact: true })).toBeHidden()
    await createTask(page, 'Neuester Einkauf')
    await openOverview(page, mobile)
    await expect(page.getByTestId('overview-task')).toHaveCount(0)
    const settings = await overviewSettings(page)
    await settings.getByLabel('Arbeit', { exact: true }).check()
    await expect(settings.getByLabel('Arbeit', { exact: true })).toBeEnabled()
    await settings.getByLabel('Einkaufen', { exact: true }).check()
    await expect(settings.getByLabel('Einkaufen', { exact: true })).toBeEnabled()
    await settings.getByRole('button', { name: 'Schließen', exact: true }).click()
    await expect(page.getByTestId('overview-task')).toHaveText([/Neuere Arbeit/, /Ältere Arbeit/, /Neuester Einkauf/])
    await setOverviewMode(page, 'newest')
    const rows = page.getByTestId('overview-task')
    await expect(rows).toHaveText([/Neuester Einkauf/, /Neuere Arbeit/, /Ältere Arbeit/])
    await expect(rows.nth(0).getByRole('img', { name: 'Liste: Einkaufen', exact: true })).toBeVisible()
    await expect(rows.nth(1).getByRole('img', { name: 'Liste: Arbeit', exact: true })).toBeVisible()
    await expect(rows.nth(0).getByTestId('list-icon')).toHaveAttribute('data-icon', 'std:shopping')
    await expect(rows.nth(1).getByTestId('list-icon')).toHaveAttribute('data-icon', 'std:prio')
    await page.screenshot({ path: test.info().outputPath('listenherkunft-dunkel.png'), animations: 'disabled' })
    await setTheme(page, mobile, 'light')
    await page.screenshot({ path: test.info().outputPath('listenherkunft-hell.png'), animations: 'disabled' })
    await setOverviewMode(page, 'by_list')
    await expect(page.getByTestId('overview-task')).toHaveText([/Neuere Arbeit/, /Ältere Arbeit/, /Neuester Einkauf/])
  })

  test('erste Erfassung verlangt ein Ziel, danach wird nur die letzte Gesamt-Zielliste gemerkt', async ({ page, request }) => {
    await register(page, desktop.uniqueEmail('overview-target'))
    await createList(page, 'Arbeit')
    await openOverview(page, mobile)
    if (mobile) await page.getByRole('button', { name: 'Neue Aufgabe', exact: true }).click()
    const composer = page.getByRole('form', { name: 'Neue Aufgabe anlegen', exact: true })
    const title = composer.getByLabel('Neue Aufgabe', { exact: true })
    await title.fill('Bewusst ausgeschlossene Aufgabe')
    await title.press('Enter')
    const target = composer.getByRole('combobox', { name: 'Zielliste', exact: true })
    await expect(target).toHaveAttribute('aria-expanded', 'true')
    await expect(title).toHaveValue('Bewusst ausgeschlossene Aufgabe')
    await selectOption(target, { label: 'Arbeit' })
    await expect(composer).toContainText('ist nicht in deiner Gesamtansicht')
    await composer.getByRole('button', { name: 'Hinzufügen', exact: true }).click()
    await expect.poll(async () => (await desktop.serverState(request)).tasks.map(task => task.title)).toEqual(['Bewusst ausgeschlossene Aufgabe'])
    await expect(page.getByTestId('overview-task')).toHaveCount(0)
    await createList(page, 'Andere Liste')
    await createTask(page, 'Eine Aufgabe außerhalb der Gesamtansicht')
    await page.reload()
    if (mobile) await page.getByRole('button', { name: 'Neue Aufgabe', exact: true }).click()
    await title.focus()
    await expect(target).toHaveText('Arbeit')
    await expect(title).toHaveValue('')
  })

  test('merkt die bevorzugte Ansicht nach Neustart und auf einem zweiten Gerät', async ({ page, browser, request }) => {
    const email = desktop.uniqueEmail('overview-remember')
    await register(page, email)
    await createList(page, 'Arbeit')
    await openOverview(page, mobile)
    await expectOverviewMode(page, 'by_list')
    const settings = await overviewSettings(page)
    await settings.getByLabel('Arbeit', { exact: true }).check()
    await expect(settings.getByLabel('Arbeit', { exact: true })).toBeEnabled()
    await settings.getByRole('button', { name: 'Schließen', exact: true }).click()
    await rememberOverviewTarget(page, mobile, 'Arbeit')
    await setOverviewMode(page, 'newest')
    await expect.poll(async () => (await desktop.serverState(request)).userPreferences[0]?.overview_mode).toBe('newest')
    await page.reload()
    await expectOverviewMode(page, 'newest')
    const otherContext = await browser.newContext({ viewport: { width: 1280, height: 800 }, hasTouch: false })
    try {
      const other = await otherContext.newPage()
      await desktop.login(other, email)
      await expectOverviewMode(other, 'newest')
      const otherSettings = await overviewSettings(other)
      await expect(otherSettings.getByLabel('Arbeit', { exact: true })).toBeChecked()
      await otherSettings.getByRole('button', { name: 'Schließen', exact: true }).click()
      await other.getByLabel('Neue Aufgabe', { exact: true }).focus()
      await expect(other.getByLabel('Zielliste', { exact: true })).toHaveText('Arbeit')
    } finally { await otherContext.close() }
  })

  test('Bereiche teilen ihre Klappstellung und Erledigt ist in beiden Ansichten erreichbar', async ({ page }) => {
    await register(page, desktop.uniqueEmail('overview-shared'))
    await createList(page, 'Einkaufen')
    await createTask(page, 'Milch')
    await createTask(page, 'Saft')
    const settings = await desktop.openListSettings(page)
    await settings.getByLabel('In Gesamtansicht aufnehmen').check()
    await expect(settings.getByLabel('In Gesamtansicht aufnehmen')).toBeEnabled()
    await settings.getByLabel('Erledigt am Listenende').check()
    await expect(settings.getByLabel('Erledigt am Listenende')).toBeEnabled()
    await desktop.closeListSettings(page)
    const sections = await desktop.listAction(page, 'Bereiche')
    await sections.getByLabel('Neuer Bereich').fill('Getränke')
    await sections.getByRole('button', { name: 'Bereich anlegen', exact: true }).click()
    await desktop.closeListSettings(page)
    for (const title of ['Milch', 'Saft']) {
      const editor = await desktop.openTaskEditor(page, title)
      await moreOptions(editor)
      await selectOption(editor.getByLabel('Bereich', { exact: true }), { label: 'Getränke' })
      await editor.getByRole('button', { name: 'Speichern', exact: true }).click()
      await expect(editor).toBeHidden()
    }
    const header = page.getByTestId('section-header').filter({ hasText: 'Getränke' })
    await header.click()
    await expect(page.getByTestId('task-row').filter({ hasText: 'Milch' })).toHaveCount(0)
    await openOverview(page, mobile)
    await expect(header).toHaveAttribute('aria-expanded', 'false')
    await expect(page.getByTestId('overview-task')).toHaveCount(0)
    await header.click()
    await page.getByLabel('Aufgabe erledigen: Milch', { exact: true }).click()
    const done = page.getByRole('region', { name: 'Erledigt', exact: true })
    await expect(done.getByRole('button', { name: 'Erledigt 1', exact: true })).toHaveAttribute('aria-expanded', 'false')
    await done.getByRole('button', { name: 'Erledigt 1', exact: true }).click()
    await expect(done.getByTestId('task-row')).toHaveText('Milch')
    await page.getByRole('button', { name: /^Liste Einkaufen öffnen$/ }).click()
    await expect(header).toHaveAttribute('aria-expanded', 'true')
    await expect(done.getByRole('button', { name: 'Erledigt 1', exact: true })).toHaveAttribute('aria-expanded', 'false')
    await openOverview(page, mobile)
    await setOverviewMode(page, 'newest')
    await expect(done.getByRole('button', { name: 'Erledigt 1', exact: true })).toHaveAttribute('aria-expanded', 'false')
    await done.getByRole('button', { name: 'Erledigt 1', exact: true }).click()
    await expect(done.getByRole('img', { name: 'Liste: Einkaufen', exact: true })).toBeVisible()
    const reopen = done.getByRole('checkbox', { name: 'Aufgabe wieder öffnen: Milch', exact: true })
    await expect(reopen).toBeChecked()
    await reopen.click()
    await expect(page.getByTestId('overview-task')).toHaveCount(2)
  })

  if (!mobile) test('Gesamtentwurf bleibt unabhängig von den Entwürfen der einzelnen Listen', async ({ page }) => {
    await register(page, desktop.uniqueEmail('overview-drafts'))
    await createList(page, 'Einkaufen')
    await page.getByLabel('Neue Aufgabe', { exact: true }).fill('Milch noch nicht gespeichert')
    await createList(page, 'Arbeit')
    await expect(page.getByLabel('Neue Aufgabe', { exact: true })).toHaveValue('')
    await page.getByLabel('Neue Aufgabe', { exact: true }).fill('Bericht noch nicht gespeichert')
    await openOverview(page, false)
    const target = page.getByLabel('Zielliste', { exact: true })
    const title = page.getByLabel('Neue Aufgabe', { exact: true })
    await title.focus()
    await selectOption(target, { label: 'Einkaufen' })
    await expect(title).toHaveValue('')
    await title.fill('Gesamtentwurf')
    await selectOption(target, { label: 'Arbeit' })
    await expect(title).toHaveValue('Gesamtentwurf')
    await desktop.selectList(page, 'Einkaufen')
    await expect(title).toHaveValue('Milch noch nicht gespeichert')
    await title.press('Enter')
    await expect(desktop.taskItem(page, 'Milch noch nicht gespeichert')).toBeVisible()
    await desktop.selectList(page, 'Arbeit')
    await expect(title).toHaveValue('Bericht noch nicht gespeichert')
    await openOverview(page, false)
    await expect(title).toHaveValue('Gesamtentwurf')
  })

  test('gleiche Titel bearbeiten die richtige Aufgabe; Editor und Entwurf überleben Breitenwechsel', async ({ page, request }, info) => {
    await register(page, desktop.uniqueEmail('overview-editor'))
    await createList(page, 'Arbeit')
    await createTask(page, 'Gleicher Titel')
    await createList(page, 'Einkaufen')
    await createTask(page, 'Gleicher Titel')
    await openOverview(page, mobile)
    const settings = await overviewSettings(page)
    for (const list of ['Arbeit', 'Einkaufen']) {
      await settings.getByLabel(list, { exact: true }).check()
      await expect(settings.getByLabel(list, { exact: true })).toBeEnabled()
    }
    await settings.getByRole('button', { name: 'Schließen', exact: true }).click()
    await page.getByRole('region', { name: 'Aufgaben aus Einkaufen' }).getByTestId('task-row').filter({ hasText: 'Gleicher Titel' }).click()
    const editor = page.getByRole('dialog', { name: 'Aufgabe', exact: true })
    await editor.getByLabel('Titel', { exact: true }).fill('Nur Einkauf geändert')
    await page.setViewportSize({ width: mobile ? 1280 : 390, height: mobile ? 800 : 844 })
    await expect(editor.getByLabel('Titel', { exact: true })).toHaveValue('Nur Einkauf geändert')
    await editor.getByRole('button', { name: 'Speichern', exact: true }).click()
    await expect(editor).toBeHidden()
    await expect.poll(async () => (await desktop.serverState(request)).tasks.map(task => task.title).sort()).toEqual(['Gleicher Titel', 'Nur Einkauf geändert'])
    await page.setViewportSize({ width: 390, height: 844 })
    await page.screenshot({ path: info.outputPath('overview-phone.png') })
    await page.setViewportSize({ width: 740, height: 360 })
    await page.screenshot({ path: info.outputPath('overview-landscape.png') })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  })
})
