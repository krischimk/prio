import { expect, test, type Page } from '@playwright/test'
import * as desktop from './helpers'
import * as phone from './mobile'
import { openOverview } from './overview'
import { selectOption } from './select'
import { setDueAt } from './taskForms'
import { formatCalendarDay } from '../../../src/ui/datetime'
import { setTheme } from './theme'
import { addChecklistPoint, outerTask } from './checklists'

export async function calendarParity(page: Page, mobile: boolean) {
  await page.clock.setFixedTime(new Date('2026-10-24T10:00:00+02:00'))
  await (mobile ? phone.register : desktop.register)(page, desktop.uniqueEmail('calendar'))
  await (mobile ? phone.createList : desktop.createList)(page, 'Termine')
  const settings = await desktop.openListSettings(page)
  await settings.getByLabel('In Gesamtansicht aufnehmen', { exact: true }).check()
  await expect(settings.getByLabel('In Gesamtansicht aufnehmen', { exact: true })).toBeEnabled()
  await desktop.closeListSettings(page)
  await (mobile ? phone.createTask : desktop.createTask)(page, 'Abgabe')
  const editor = await desktop.openTaskEditor(page, 'Abgabe')
  await setDueAt(editor, '2026-10-30T18:00')
  await editor.getByRole('button', { name: 'Speichern', exact: true }).click()
  await expect(editor).toBeHidden()
  await openOverview(page, mobile)
  await page.getByRole('button', { name: 'Kalender anzeigen', exact: true }).click()
  const calendar = page.getByRole('region', { name: 'Aufgabenkalender', exact: true })
  await expect(calendar).toBeVisible()
  await expect(calendar.getByLabel('Wiederkehrende Aufgaben', { exact: true })).toHaveAttribute('data-value', 'active')
  const day = calendar.getByRole('button', { name: formatCalendarDay('2026-10-30'), exact: true })
  await day.click()
  await expect(calendar.getByText('Abgabe', { exact: true })).toBeVisible()
  await calendar.getByRole('button', { name: 'Wenig Zeit', exact: true }).click()
  await expect(day).toHaveAttribute('data-capacity', 'low')
  await calendar.getByRole('button', { name: 'Keine Zeit', exact: true }).click()
  await expect(day).toHaveAttribute('data-capacity', 'none')
  await calendar.getByRole('button', { name: formatCalendarDay('2026-10-29'), exact: true }).click()
  await calendar.getByRole('button', { name: 'Wenig Zeit', exact: true }).click()
  await expect(calendar.getByRole('button', { name: formatCalendarDay('2026-10-29'), exact: true })).toHaveAttribute('data-capacity', 'low')
  await day.click()
  await selectOption(calendar.getByLabel('Wiederkehrende Aufgaben', { exact: true }), 'all')
  await expect(calendar.getByLabel('Wiederkehrende Aufgaben', { exact: true })).toHaveAttribute('data-value', 'all')
  await page.screenshot({ path: test.info().outputPath('kalender-dunkel.png'), animations: 'disabled' })
  if (mobile) {
    await page.setViewportSize({ width: 740, height: 390 })
    await page.screenshot({ path: test.info().outputPath('kalender-quer.png'), animations: 'disabled' })
    await page.setViewportSize({ width: 390, height: 844 })
  }
  await setTheme(page, mobile, 'light')
  await page.screenshot({ path: test.info().outputPath('kalender-hell.png'), animations: 'disabled' })
  await page.reload()
  await expect(calendar).toBeVisible()
  await day.click()
  await expect(calendar.getByRole('button', { name: 'Keine Zeit', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await calendar.getByRole('button', { name: 'Aufgabe für diesen Tag', exact: true }).click()
  const fresh = page.getByRole('dialog', { name: 'Neue Aufgabe', exact: true })
  await fresh.getByRole('button', { name: 'Fälligkeit und Wiederholung bearbeiten', exact: true }).click()
  await expect(fresh.getByLabel('Fällig am', { exact: true })).toHaveValue('30.10.2026')
  await expect(fresh.getByRole('button', { name: formatCalendarDay('2026-10-30'), exact: true })).toHaveAttribute('data-capacity', 'none')
  await page.keyboard.press('Escape')
  await page.keyboard.press('Escape')
}

export async function routineParity(page: Page, mobile: boolean) {
  await page.clock.setFixedTime(new Date('2026-10-24T10:00:00+02:00'))
  await (mobile ? phone.register : desktop.register)(page, desktop.uniqueEmail('routine'))
  await (mobile ? phone.createList : desktop.createList)(page, 'Routinen')
  await (mobile ? phone.createTask : desktop.createTask)(page, 'Morgens lesen')
  const editor = await desktop.openTaskEditor(page, 'Morgens lesen')
  await addChecklistPoint(editor, 'Ein paar Seiten lesen')
  await editor.getByRole('textbox', { name: 'Notiz', exact: true }).fill('Erster Absatz.\n\nZweiter Absatz.')
  await setDueAt(editor, '2026-10-24T22:30')
  await selectOption(editor.getByLabel('Wiederholung', { exact: true }), 'daily')
  await selectOption(editor.getByLabel('Sichtbarkeit der Wiederholungen', { exact: true }), 'clock')
  await expect(editor.getByLabel('Sichtbar ab', { exact: true })).toHaveValue('05:00')
  await editor.getByLabel('Beim nächsten Durchlauf neu beginnen', { exact: true }).check()
  await editor.getByRole('button', { name: 'Speichern', exact: true }).click()
  await expect(editor).toBeHidden()
  const row = outerTask(page, 'Morgens lesen')
  await row.getByRole('button', { name: 'Checkliste: Morgens lesen', exact: true }).click()
  await row.getByRole('button', { name: 'Notiz aufklappen', exact: true }).click()
  await expect(row.getByRole('button', { name: 'Notiz einklappen', exact: true })).toBeVisible()
  await expect(row.getByRole('checkbox', { name: 'Checklistenpunkt: Ein paar Seiten lesen', exact: true })).toBeVisible()
  await page.screenshot({ path: test.info().outputPath('checklistenabstand-und-absatz.png'), animations: 'disabled' })
  await page.getByRole('checkbox', { name: 'Aufgabe erledigen: Morgens lesen', exact: true }).click()
  await expect(page.getByRole('checkbox', { name: 'Aufgabe erledigen: Morgens lesen', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Rückgängig', exact: true }).click()
  await expect(page.getByRole('checkbox', { name: 'Aufgabe erledigen: Morgens lesen', exact: true })).toBeVisible()
  await desktop.openTaskEditor(page, 'Morgens lesen')
  await editor.getByRole('button', { name: 'Fälligkeit und Wiederholung bearbeiten', exact: true }).click()
  await expect(editor.getByLabel('Sichtbarkeit der Wiederholungen', { exact: true })).toHaveAttribute('data-value', 'clock')
  await selectOption(editor.getByLabel('Sichtbarkeit der Wiederholungen', { exact: true }), 'lead')
  await expect(editor.getByLabel('Sichtbarkeit: Vorlauf', { exact: true })).toHaveValue('12')
  await page.screenshot({ path: test.info().outputPath('routine-vorlauf.png'), animations: 'disabled' })
  await editor.getByRole('button', { name: 'Speichern', exact: true }).click()
  await expect(editor).toBeHidden()
}
