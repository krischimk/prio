import { expect, test, type Page } from '@playwright/test'
import * as desktop from './helpers'
import * as phone from './mobile'
import { addChecklistPoint, outerTask } from './checklists'
import { setDueAt } from './taskForms'

export async function ratingParity(page: Page, mobile: boolean) {
  await (mobile ? phone.register : desktop.register)(page, desktop.uniqueEmail('rating'))
  await (mobile ? phone.createList : desktop.createList)(page, 'Bewertbar')
  await (mobile ? phone.createTask : desktop.createTask)(page, 'Einschätzung')
  const editor = await desktop.openTaskEditor(page, 'Einschätzung')
  await expect(editor.getByRole('slider', { name: 'Wichtigkeit einschätzen', exact: true })).toBeVisible()
  await expect(editor.getByRole('slider', { name: 'Aufwand', exact: true })).toHaveCount(0)
  await setDueAt(editor, '2030-12-18T18:00')
  await expect(editor.getByRole('slider', { name: 'Aufwand', exact: true })).toHaveCount(0)
  // Ein Klick genau auf den schon intern mittigen Regler muss ebenfalls starten.
  const importance = editor.getByRole('slider', { name: 'Wichtigkeit einschätzen', exact: true })
  await importance.click({ position: { x: (await importance.boundingBox())!.width / 2, y: 20 } })
  await expect(editor.getByRole('slider', { name: 'Aufwand', exact: true })).toHaveValue('5')
  await expect(editor.getByRole('slider', { name: 'Dringlichkeit', exact: true })).toBeDisabled()
  await editor.getByRole('button', { name: 'Manuell', exact: true }).click()
  await editor.getByRole('slider', { name: 'Dringlichkeit', exact: true }).press('Home')
  await editor.getByRole('slider', { name: 'Aufwand', exact: true }).press('End')
  await editor.getByRole('slider', { name: 'Wichtigkeit', exact: true }).press('End')
  await editor.getByLabel('Titel', { exact: true }).press('Control+Enter')
  await expect(editor).toBeHidden()
  const row = outerTask(page, 'Einschätzung')
  await expect(row.getByRole('meter', { name: 'Wichtigkeit', exact: true })).toHaveAttribute('aria-valuenow', '10')
  await expect(row.getByRole('meter', { name: 'Dringlichkeit', exact: true })).toHaveAttribute('aria-valuenow', '0')
  const settings = await desktop.openListSettings(page)
  await settings.getByLabel('Bewertungen verwenden', { exact: true }).uncheck()
  await expect(settings.getByLabel('Bewertungen verwenden', { exact: true })).toBeEnabled()
  await desktop.closeListSettings(page)
  await expect(row.getByRole('meter')).toHaveCount(0)
  await desktop.openTaskEditor(page, 'Einschätzung')
  await expect(editor.getByRole('slider')).toHaveCount(0)
  await editor.getByRole('button', { name: 'Schließen', exact: true }).click()
  await desktop.openListSettings(page)
  await settings.getByLabel('Bewertungen verwenden', { exact: true }).check()
  await expect(settings.getByLabel('Bewertungen verwenden', { exact: true })).toBeEnabled()
  await desktop.closeListSettings(page)
  await expect(row.getByRole('meter', { name: 'Aufwand', exact: true })).toHaveAttribute('aria-valuenow', '10')
  await desktop.openTaskEditor(page, 'Einschätzung')
  await editor.getByRole('button', { name: 'Bewertung entfernen', exact: true }).click()
  await expect(editor.getByRole('slider', { name: 'Wichtigkeit einschätzen', exact: true })).toBeVisible()
  await expect(editor.getByRole('slider', { name: 'Aufwand', exact: true })).toHaveCount(0)
  await editor.getByRole('button', { name: 'Speichern', exact: true }).click()
  await expect(row.getByRole('meter')).toHaveCount(0)
}

export async function weightedChecklistParity(page: Page, mobile: boolean) {
  await (mobile ? phone.register : desktop.register)(page, desktop.uniqueEmail('weighted'))
  await (mobile ? phone.createList : desktop.createList)(page, 'Gewichtete Schritte')
  await (mobile ? phone.createTask : desktop.createTask)(page, 'Projekt vorbereiten')
  const editor = await desktop.openTaskEditor(page, 'Projekt vorbereiten')
  await addChecklistPoint(editor, 'Recherche')
  await addChecklistPoint(editor, 'Zusammenfassung')
  await expect(editor.getByRole('slider', { name: /^Gewichtung:/ })).toHaveCount(0)
  await editor.getByRole('slider', { name: 'Wichtigkeit einschätzen', exact: true }).press('End')
  const linked = editor.getByLabel('Checkliste reduziert den Restaufwand', { exact: true })
  await expect(linked).toBeChecked()
  const first = editor.getByRole('slider', { name: 'Gewichtung: Recherche', exact: true })
  await expect(first).toHaveValue('0.5')
  await first.press('End')
  for (let i = 0; i < 25; i++) await first.press('ArrowLeft')
  await expect(first).toHaveValue('0.75')
  await expect(editor.getByRole('slider', { name: 'Gewichtung: Zusammenfassung', exact: true })).toHaveValue('0.25')
  await editor.getByRole('slider', { name: 'Gesamtaufwand', exact: true }).press('End')
  await addChecklistPoint(editor, 'Temporärer Punkt')
  await expect(first).toHaveValue('0.5')
  await editor.getByRole('button', { name: 'Checklistenpunkt löschen: Temporärer Punkt', exact: true }).click()
  await expect(first).toHaveValue('0.75')
  await editor.getByRole('button', { name: 'Speichern', exact: true }).click()
  const row = outerTask(page, 'Projekt vorbereiten')
  await row.getByRole('button', { name: 'Checkliste: Projekt vorbereiten', exact: true }).click()
  await row.getByLabel('Checklistenpunkt: Recherche', { exact: true }).check()
  await expect(row.getByRole('meter', { name: 'Restaufwand', exact: true })).toHaveAttribute('aria-valuenow', '2.5')
  await row.getByLabel('Checklistenpunkt: Zusammenfassung', { exact: true }).check()
  await expect(row.getByRole('meter', { name: 'Restaufwand', exact: true })).toHaveAttribute('aria-valuenow', '0')
  await expect(row.getByLabel('Aufgabe erledigen: Projekt vorbereiten', { exact: true })).not.toBeChecked()
  await row.getByLabel('Checklistenpunkt: Recherche', { exact: true }).uncheck()
  await expect.poll(async () => Number(await row.getByRole('meter', { name: 'Restaufwand', exact: true }).getAttribute('aria-valuenow'))).toBeCloseTo(7.5)
  await desktop.openTaskEditor(page, 'Projekt vorbereiten')
  await expect(linked).toBeChecked()
  await expect(first).toHaveValue('0.75')
  await page.screenshot({ path: test.info().outputPath('gewichtete-checkliste-dunkel.png') })
  await editor.getByRole('meter', { name: 'Priorität', exact: true }).scrollIntoViewIfNeeded()
  await page.screenshot({ path: test.info().outputPath('bewertung-dunkel.png') })
  if (mobile) {
    await page.setViewportSize({ width: 740, height: 360 })
    await page.screenshot({ path: test.info().outputPath('gewichtete-checkliste-quer.png') })
    await page.setViewportSize({ width: 390, height: 844 })
  }
  await linked.uncheck()
  await expect(editor.getByRole('slider', { name: /^Gewichtung:/ })).toHaveCount(0)
  await editor.getByRole('button', { name: 'Speichern', exact: true }).click()
  await expect(row.getByRole('meter', { name: 'Aufwand', exact: true })).toHaveAttribute('aria-valuenow', '10')
  await page.reload()
  if (mobile) { await phone.openMenu(page); await page.getByRole('dialog', { name: 'Menü' }).getByRole('button', { name: /^Gewichtete Schritte$/ }).click() }
  else await desktop.selectList(page, 'Gewichtete Schritte')
  await desktop.openTaskEditor(page, 'Projekt vorbereiten')
  await expect(linked).not.toBeChecked()
  await linked.check()
  await expect(first).toHaveValue('0.75')
  await expect.poll(async () => Number(await editor.getByRole('meter', { name: 'Restaufwand', exact: true }).getAttribute('aria-valuenow'))).toBeCloseTo(7.5)
  await editor.getByRole('button', { name: 'Speichern', exact: true }).click()
  await expect(editor).toBeHidden()
  if (mobile) await phone.openMenu(page)
  await page.getByRole('button', { name: 'Hellen Modus einschalten', exact: true }).click()
  if (mobile) await page.getByRole('dialog', { name: 'Menü', exact: true }).getByRole('button', { name: /^Gewichtete Schritte$/ }).click()
  await desktop.openTaskEditor(page, 'Projekt vorbereiten')
  await editor.getByRole('meter', { name: 'Priorität', exact: true }).scrollIntoViewIfNeeded()
  await page.screenshot({ path: test.info().outputPath('bewertung-hell.png') })
}
